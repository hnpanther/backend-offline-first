-- =============================================================================
-- V19 — log-sheet categories: «which kind of work is this round» (roadmap §28)
--
-- WHAT CHANGES.
--   * `log_sheet_categories` — a small master-data table: code, name, active.
--   * `log_sheet_templates.category_id` — the category every round the template raises gets.
--   * `log_sheets.category_id` + `log_sheets.category_name` — FROZEN onto the round when it is
--     raised, from the template or from the custom-sheet form.
--   * Four `master-data` permissions for the category page, granted to every role that may
--     already create a log-sheet template.
--
-- WHY A TABLE, NOT A FREE-TEXT COLUMN. A round with equipment can be grouped by its asset class;
-- an asset-less round («چک‌لیست واحد ایمنی», «چک‌لیست حراست») has nothing but `template_name`, a
-- string somebody typed. Free text degrades the way it always does — «ایمنی», «واحد ایمنی», «HSE»
-- and «ایمنی ‌» are four groups by the end of the first year, and no report can be trusted
-- afterwards. The plant already learned this with asset names: 507 spellings for 1,555 pumps
-- (roadmap §20). Reusing `asset_classes` was rejected too: a checklist is not a piece of
-- equipment, and an empty class looks like a data problem on the asset pages.
--
-- WHY THE NAME IS FROZEN BESIDE THE ID. The id is for filtering and grouping; the NAME is what
-- the round says it was, for the same reason `asset_name` is frozen onto an entry: a category
-- renamed next year must not rewrite what this year's rounds were called. `ck_log_sheets_category_frozen`
-- makes the pair all-or-nothing, so a reader never meets an id with no name or a name with no id.
--
-- WHY THE FOREIGN KEYS STAY (and deleting is refused, not cascaded). A category that rounds or
-- templates still name cannot disappear: it would leave grouping ids that resolve to nothing.
-- The service refuses the delete with a sentence before the database would (AGENTS.md #167 —
-- a guard must check EVERY referencing column), and offers «غیرفعال» instead, which keeps the
-- history and only takes the category out of the pickers.
--
-- COST ON A LARGE `log_sheets`. Both new columns are nullable with no default, so adding them is
-- a catalogue change, not a rewrite. The CHECK and the partial index each read the table once;
-- on the operational database's row count that is well under a second, and it happens at boot
-- before any request is served. Existing rounds stay uncategorised (NULL) — nothing is guessed
-- from a template name, because a guess is exactly the free-text grouping this table replaces.
--
-- DERIVED GRANTS, NOT ROLE CODES. The page is granted to whoever holds `POST:/log-sheet-templates`
-- (ADMIN and HIGH_USER on the seeded roles), so a role duplicated from either inherits it
-- (docs/security.md §3; same rule as V9, V16, V17).
-- =============================================================================

CREATE TABLE log_sheet_categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(50)  NOT NULL,
    name       VARCHAR(255) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at BIGINT,
    updated_at BIGINT,
    CONSTRAINT ck_log_sheet_categories_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT ck_log_sheet_categories_name_not_blank CHECK (btrim(name) <> '')
);

-- Case-insensitive, like every other code in this schema: «safety» and «SAFETY» are one category.
CREATE UNIQUE INDEX ux_log_sheet_categories_code_lower ON log_sheet_categories (lower(code));

ALTER TABLE log_sheet_templates
    ADD COLUMN category_id BIGINT
        CONSTRAINT fk_log_sheet_templates_category REFERENCES log_sheet_categories (id);

CREATE INDEX idx_log_sheet_templates_category_id
    ON log_sheet_templates (category_id) WHERE category_id IS NOT NULL;

ALTER TABLE log_sheets
    ADD COLUMN category_id BIGINT
        CONSTRAINT fk_log_sheets_category REFERENCES log_sheet_categories (id);

ALTER TABLE log_sheets
    ADD COLUMN category_name VARCHAR(255);

ALTER TABLE log_sheets
    ADD CONSTRAINT ck_log_sheets_category_frozen
        CHECK ((category_id IS NULL) = (category_name IS NULL));

-- Serves the list's «دسته» filter and the delete guard's «is it still named» probe. Partial,
-- because uncategorised rounds — every round before V19 — are never looked up by category.
CREATE INDEX idx_log_sheets_category_id
    ON log_sheets (category_id) WHERE category_id IS NOT NULL;

INSERT INTO permissions (code, name, category, http_method, endpoint_path) VALUES
('GET:/log-sheet-categories',              'مشاهده دسته‌های لاگ‌شیت', 'master-data', 'GET',  '/log-sheet-categories'),
('POST:/log-sheet-categories',             'ایجاد دسته لاگ‌شیت',      'master-data', 'POST', '/log-sheet-categories'),
('POST:/log-sheet-categories/{id}',        'ویرایش دسته لاگ‌شیت',     'master-data', 'POST', '/log-sheet-categories/{id}'),
('POST:/log-sheet-categories/{id}/delete', 'حذف دسته لاگ‌شیت',        'master-data', 'POST', '/log-sheet-categories/{id}/delete');

INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, p.id
  FROM role_permissions rp
  JOIN permissions src ON src.id = rp.permission_id
                      AND src.code = 'POST:/log-sheet-templates'
 CROSS JOIN permissions p
 WHERE p.code IN ('GET:/log-sheet-categories',
                  'POST:/log-sheet-categories',
                  'POST:/log-sheet-categories/{id}',
                  'POST:/log-sheet-categories/{id}/delete')
ON CONFLICT (role_id, permission_id) DO NOTHING;
