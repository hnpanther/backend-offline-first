-- =============================================================================
-- V31 — form submission reopen (SUBMITTED → DRAFT) + answer revision history
--
-- WHAT. A subject-unit supervisor may reopen a SUBMITTED filing to editable DRAFT
-- so answers can be corrected on the panel (mirrors log-sheet ADMIN_REOPEN). The
-- prior submission's form_data is kept in form_submission_revisions before any
-- overwrite — same shape as log_sheet_revisions. REOPEN is recorded on the
-- existing action log.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Action log: REOPEN
-- -----------------------------------------------------------------------------
ALTER TABLE form_submission_action_log DROP CONSTRAINT IF EXISTS ck_form_submission_action_log_action;
ALTER TABLE form_submission_action_log
    ADD CONSTRAINT ck_form_submission_action_log_action
        CHECK (action IN ('APPROVE', 'UNAPPROVE', 'VOID', 'UNVOID', 'REOPEN'));

-- -----------------------------------------------------------------------------
-- 2. Revisions of superseded answers (append-only; old value only)
-- -----------------------------------------------------------------------------
CREATE TABLE form_submission_revisions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_submission_id      BIGINT       NOT NULL REFERENCES form_submissions (id) ON DELETE CASCADE,
    form_data               JSONB        NOT NULL,
    recorded_by_user_id     BIGINT       REFERENCES users (id) ON DELETE RESTRICT,
    recorded_at             BIGINT,
    superseded_by_user_id   BIGINT       REFERENCES users (id) ON DELETE RESTRICT,
    superseded_at           BIGINT       NOT NULL,
    superseded_source       VARCHAR(20)  NOT NULL,
    submission_status       VARCHAR(20)  NOT NULL
);

CREATE INDEX idx_fsr_submission ON form_submission_revisions (form_submission_id, id DESC);

-- -----------------------------------------------------------------------------
-- 3. Permission — reopen, derived from log-sheet reopen holders
-- -----------------------------------------------------------------------------
INSERT INTO permissions (code, name, category, http_method, endpoint_path) VALUES
('POST:/form-submissions/{id}/reopen', 'ارسال‌های فرم — باز کردن مجدد', 'log-sheet', 'POST', '/form-submissions/{id}/reopen');

INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, p.id
FROM role_permissions rp
JOIN permissions seed ON seed.id = rp.permission_id AND seed.code = 'POST:/log-sheets/{id}/reopen'
CROSS JOIN permissions p
WHERE p.code = 'POST:/form-submissions/{id}/reopen'
ON CONFLICT (role_id, permission_id) DO NOTHING;
