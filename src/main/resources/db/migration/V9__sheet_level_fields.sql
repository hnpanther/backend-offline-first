-- =============================================================================
-- V9 — a log sheet's own fields: questions that belong to the round, not to an asset
--
-- Designed in docs/roadmap.md §24 (which is §22a carried to the point of building it). The
-- short version: `asset_classes` + `field_definitions` is already a form builder, and what was
-- missing was a CARRIER for a form that is not "one asset inside one round". This adds that
-- carrier, mirroring the three parts the per-asset form already has:
--
--     the questions   field_definitions.class_id      ->  log_sheet_fields (owner)
--     frozen at raise log_sheets.field_definitions_snapshot
--                                                     ->  log_sheets.sheet_field_definitions_snapshot
--     the answers     log_sheet_entries.form_data     ->  log_sheets.sheet_form_data
--
-- NOTHING IS REQUIRED IN THIS RELEASE. `required` exists on the table and is honoured by the
-- validator, but no UI offers it yet and no path refuses a completion over it. That is the
-- decision that makes the rollout safe in either order: §22a records that a required question an
-- older tablet cannot answer leaves an operator stuck in the field with a refused submit.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. The questions
--
-- The columns of `field_definitions`, with a polymorphic owner instead of `class_id`: a
-- TEMPLATE (every round raised from it asks these) or a SHEET (this one round asks these).
-- `synced` is deliberately absent — it is a leftover of the master-data-editing era of the
-- mobile app, and nothing has written it for a long time (docs/schema.md).
-- -----------------------------------------------------------------------------
CREATE TABLE log_sheet_fields (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id   BIGINT REFERENCES log_sheet_templates(id) ON DELETE CASCADE,
    log_sheet_id  BIGINT REFERENCES log_sheets(id)          ON DELETE CASCADE,
    field_key     VARCHAR(255) NOT NULL,
    label         VARCHAR(255),
    data_type     VARCHAR(255),
    unit          VARCHAR(255),
    required      BOOLEAN NOT NULL DEFAULT FALSE,
    validation    JSONB,
    sort_order    INTEGER,
    version       INTEGER,
    deleted       BOOLEAN NOT NULL DEFAULT FALSE,
    created_at    BIGINT,
    updated_at    BIGINT,

    -- Exactly one owner. A row owned by both would be asked twice on the same round and edited
    -- from two pages, and neither of those failures announces itself.
    CONSTRAINT ck_log_sheet_fields_one_owner
        CHECK ((template_id IS NOT NULL) <> (log_sheet_id IS NOT NULL))
);

-- One live definition per key per owner.
--
-- THESE ARE PARTIAL ON *WHICH OWNER COLUMN IS POPULATED*, NEVER ON `deleted`, and the difference
-- is the whole of roadmap §23: a partial-on-deleted index would allow two definitions of one key
-- — one switched off, one new — and a stored answer would then belong to neither in particular.
-- The key would stop being an identity and become a label, which is the failure AGENTS.md #157
-- and migration V6 exist to recover from. The practical consequence is correct and intended:
-- after switching a question off, that key cannot be CREATED again, it must be switched back on.
CREATE UNIQUE INDEX ux_log_sheet_fields_template_key_lower
    ON log_sheet_fields (template_id, lower(field_key)) WHERE template_id IS NOT NULL;
CREATE UNIQUE INDEX ux_log_sheet_fields_sheet_key_lower
    ON log_sheet_fields (log_sheet_id, lower(field_key)) WHERE log_sheet_id IS NOT NULL;


-- -----------------------------------------------------------------------------
-- 2. The snapshot, the answers, and who gave them
--
-- All nullable, so every existing row stays byte-identical and every sheet raised before this
-- release renders and completes exactly as it did.
-- -----------------------------------------------------------------------------
ALTER TABLE log_sheets ADD COLUMN sheet_field_definitions_snapshot JSONB;
ALTER TABLE log_sheets ADD COLUMN sheet_form_data                  JSONB;

-- Who answered the sheet's OWN questions, and when.
--
-- NOT `draft_saved_by_user_id`. That column moves on every per-asset dialog save and on every
-- tablet progress push, so reusing it would credit a round-level answer to whoever last touched
-- any asset on the round — the attribution error V4's revision table exists to repair, in a new
-- place. `sheet_form_source` is WEB or MOBILE, for the same reason `draft_source` was added once
-- that column had two writers.
ALTER TABLE log_sheets ADD COLUMN sheet_form_filled_by_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT;
ALTER TABLE log_sheets ADD COLUMN sheet_form_updated_at        BIGINT;
ALTER TABLE log_sheets ADD COLUMN sheet_form_source            VARCHAR(20);

COMMENT ON COLUMN log_sheets.sheet_field_definitions_snapshot IS
    'The sheet-level questions frozen when this round was raised. Editing the template later '
    'must not re-describe a round already walked — the same rule as field_definitions_snapshot.';
COMMENT ON COLUMN log_sheets.sheet_form_data IS
    'Answers to this round own questions, keyed by field_key. Unanswered keys are not stored.';


-- -----------------------------------------------------------------------------
-- 3. What a correction to those answers replaced
--
-- A sibling of `log_sheet_entry_revisions`, with the same three properties: append-only, holds
-- the OLD value, and writes NOTHING on a first fill — which is what keeps the table proportional
-- to corrections rather than to readings.
--
-- A SIBLING TABLE RATHER THAN A NULLABLE FK on the existing one. The thing worth sharing is the
-- renderer, and it is already shared and already owner-agnostic: `form-data-display ::
-- tableRevision` takes a bare map and a bare definition list. Making
-- `log_sheet_entry_revisions.log_sheet_entry_id` nullable instead would make every existing
-- query say which kind of row it means — and `findForSheetByEntryId` groups BY that id, so
-- sheet-level rows would land under a null key in a map the detail page reads by entry id.
--
-- No `entry_source`: nobody scans a tag to answer a round-level question. No
-- `attachment_snapshot`: this release does not allow attachment types at sheet level, because
-- `attachments.asset_id` is NOT NULL and a round-level photo has no asset (roadmap §24, §22c).
-- Both are one nullable column if that changes.
-- -----------------------------------------------------------------------------
CREATE TABLE log_sheet_revisions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_sheet_id          BIGINT NOT NULL REFERENCES log_sheets(id) ON DELETE CASCADE,
    form_data             JSONB  NOT NULL,
    recorded_by_user_id   BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    recorded_at           BIGINT,
    superseded_by_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    superseded_at         BIGINT NOT NULL,
    superseded_source     VARCHAR(20),
    sheet_status          VARCHAR(30),

    CONSTRAINT ck_lsr_superseded_source
        CHECK (superseded_source IS NULL OR superseded_source IN ('WEB','MOBILE','SERVER'))
);

-- One sheet's history, oldest first. The identity column orders the revisions of one sheet
-- correctly without depending on a timestamp two paths could write out of order — the same
-- reasoning as `idx_lser_entry`.
CREATE INDEX idx_lsr_sheet ON log_sheet_revisions (log_sheet_id, id DESC);


-- -----------------------------------------------------------------------------
-- 4. The editor's permissions
--
-- An endpoint with no row in `permissions` is a path no administrator can grant and no auditor
-- can see — the Roles page is built by reading this table. (AGENTS.md #9; V7 is the precedent.)
--
-- Granted to whoever may already EDIT A TEMPLATE, derived from that grant rather than written as
-- a list of role codes: a duplicated role has a new code and the same permissions, and a code
-- list would leave the copy able to rename a template and unable to edit its questions. V1's
-- blanket CROSS JOIN to ADMIN was a one-time snapshot and does not reach rows inserted here, so
-- ADMIN arrives through the same rule. SUPERVISOR holds templates read-only and therefore gets
-- none of these, which is the existing split (docs/security.md §5 F2).
-- -----------------------------------------------------------------------------
INSERT INTO permissions (code, name, category, http_method, endpoint_path) VALUES
('GET:/log-sheet-templates/{id}/fields',
 'مشاهده پرسش‌های قالب لاگ‌شیت', 'master-data', 'GET',  '/log-sheet-templates/{id}/fields'),
('POST:/log-sheet-templates/{id}/fields',
 'افزودن پرسش به قالب لاگ‌شیت', 'master-data', 'POST', '/log-sheet-templates/{id}/fields'),
('POST:/log-sheet-templates/{id}/fields/{fieldId}',
 'ویرایش پرسش قالب لاگ‌شیت', 'master-data', 'POST', '/log-sheet-templates/{id}/fields/{fieldId}'),
('POST:/log-sheet-templates/{id}/fields/{fieldId}/state',
 'فعال/غیرفعال کردن پرسش قالب لاگ‌شیت', 'master-data', 'POST', '/log-sheet-templates/{id}/fields/{fieldId}/state'),
('POST:/log-sheet-templates/{id}/fields/{fieldId}/delete',
 'حذف پرسش قالب لاگ‌شیت', 'master-data', 'POST', '/log-sheet-templates/{id}/fields/{fieldId}/delete');

INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, p.id
  FROM role_permissions rp
  JOIN permissions edit ON edit.id = rp.permission_id
                       AND edit.code = 'POST:/log-sheet-templates/{id}'
 CROSS JOIN permissions p
 WHERE p.code IN ('GET:/log-sheet-templates/{id}/fields',
                  'POST:/log-sheet-templates/{id}/fields',
                  'POST:/log-sheet-templates/{id}/fields/{fieldId}',
                  'POST:/log-sheet-templates/{id}/fields/{fieldId}/state',
                  'POST:/log-sheet-templates/{id}/fields/{fieldId}/delete')
ON CONFLICT (role_id, permission_id) DO NOTHING;
