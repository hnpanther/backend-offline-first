FROM role_permissions rp
JOIN permissions seed ON seed.id = rp.permission_id AND seed.code = 'GET:/log-sheets'
CROSS JOIN permissions p
WHERE p.code IN ('GET:/form-submissions', 'GET:/form-submissions/{id}')
