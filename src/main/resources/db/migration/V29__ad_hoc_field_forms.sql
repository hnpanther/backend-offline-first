-- =============================================================================
-- V29 — ad-hoc field forms (carrier 3): definitions, unit links, submissions,
--       and attachments that may belong to a submission instead of a log sheet
--
-- Roadmap §39 carrier 3 / §22c; plan: field-form-infra-plan.md.
--
-- WHAT THIS IS. A form an observer starts themselves — not a scheduled round.
-- ADMIN authors the definition; operators FILL; supervisors VIEW by reporter
-- unit and/or subject unit. Schema freezes on the first draft save. Final
-- submit is immutable. Lookups declared by fillable forms lease to the tablet
-- at login (extends LookupGrantService; no new permission for that half).
--
-- WHAT THIS IS NOT. Not a log sheet, not an unscheduled round, not a second
-- field DSL. Fields reuse the same columns / FieldDefinitionSnapshot /
-- FormDataValidationSupport path as log_sheet_fields.
--
-- ATTACHMENTS. log_sheet_id becomes nullable; form_submission_id is added;
-- exactly one of the two owners must be set. Void evidence stays log-sheet-
-- owned (void_submission_id still implies a log_sheet_id).
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. Form definitions (ADMIN authors)
-- -----------------------------------------------------------------------------
CREATE TABLE form_definitions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(100)  NOT NULL,
    title       VARCHAR(255)  NOT NULL,
    description VARCHAR(2000),
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  BIGINT        NOT NULL,
    updated_at  BIGINT        NOT NULL,
    created_by_user_id BIGINT REFERENCES users (id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX ux_form_definitions_code_lower ON form_definitions (lower(code));
CREATE INDEX idx_form_definitions_active ON form_definitions (active);


-- -----------------------------------------------------------------------------
-- 2. Units that may appear as subject_unit_id when filling the form
--    (cross-unit filing: reporter need not belong to the subject unit)
-- -----------------------------------------------------------------------------
CREATE TABLE form_definition_units (
    form_definition_id BIGINT NOT NULL REFERENCES form_definitions (id) ON DELETE CASCADE,
    operational_unit_id BIGINT NOT NULL REFERENCES operational_units (id) ON DELETE RESTRICT,
    PRIMARY KEY (form_definition_id, operational_unit_id)
);

CREATE INDEX idx_form_definition_units_unit ON form_definition_units (operational_unit_id);


-- -----------------------------------------------------------------------------
-- 3. Form fields — sibling of log_sheet_fields; same columns, one owner
--    Unique index is NON-partial on deleted (roadmap §23 / AGENTS #157).
-- -----------------------------------------------------------------------------
CREATE TABLE form_fields (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_definition_id BIGINT       NOT NULL REFERENCES form_definitions (id) ON DELETE CASCADE,
    field_key          VARCHAR(255) NOT NULL,
    label              VARCHAR(255),
    data_type          VARCHAR(255),
    unit               VARCHAR(255),
    required           BOOLEAN      NOT NULL DEFAULT FALSE,
    validation         JSONB,
    sort_order         INTEGER,
    version            INTEGER,
    deleted            BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at         BIGINT,
    updated_at         BIGINT
);

CREATE UNIQUE INDEX ux_form_fields_form_key_lower
    ON form_fields (form_definition_id, lower(field_key));
CREATE INDEX idx_form_fields_form_id ON form_fields (form_definition_id);


-- -----------------------------------------------------------------------------
-- 4. Submissions — DRAFT (mutable) → SUBMITTED (immutable)
--    Snapshot freezes on first draft save. client_action_id is submit idempotency.
-- -----------------------------------------------------------------------------
CREATE TABLE form_submissions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_definition_id      BIGINT       NOT NULL REFERENCES form_definitions (id) ON DELETE RESTRICT,
    status                  VARCHAR(20)  NOT NULL,
    reporter_unit_id        BIGINT       NOT NULL REFERENCES operational_units (id) ON DELETE RESTRICT,
    subject_unit_id         BIGINT       NOT NULL REFERENCES operational_units (id) ON DELETE RESTRICT,
    form_data               JSONB,
    field_definitions_snapshot JSONB,
    reported_by_user_id     BIGINT       REFERENCES users (id) ON DELETE RESTRICT,
    reported_by_name        VARCHAR(255),
    source                  VARCHAR(20)  NOT NULL,
    local_id                VARCHAR(255),
    client_action_id        VARCHAR(255),
    draft_client_action_id  VARCHAR(255),
    created_at              BIGINT       NOT NULL,
    updated_at              BIGINT       NOT NULL,
    submitted_at            BIGINT,
    synced_at               BIGINT,
    device_time_at          BIGINT,
    CONSTRAINT ck_form_submissions_status CHECK (status IN ('DRAFT', 'SUBMITTED'))
);

CREATE UNIQUE INDEX ux_form_submissions_client_action_id
    ON form_submissions (client_action_id) WHERE client_action_id IS NOT NULL;
CREATE UNIQUE INDEX ux_form_submissions_local_id_user
    ON form_submissions (reported_by_user_id, local_id)
    WHERE local_id IS NOT NULL AND reported_by_user_id IS NOT NULL;
CREATE INDEX idx_form_submissions_form_status ON form_submissions (form_definition_id, status);
CREATE INDEX idx_form_submissions_reporter_unit ON form_submissions (reporter_unit_id, updated_at DESC);
CREATE INDEX idx_form_submissions_subject_unit ON form_submissions (subject_unit_id, updated_at DESC);
CREATE INDEX idx_form_submissions_reporter ON form_submissions (reported_by_user_id, updated_at DESC);


-- -----------------------------------------------------------------------------
-- 5. Attachments — exactly one owner: log sheet XOR form submission
-- -----------------------------------------------------------------------------
ALTER TABLE attachments ALTER COLUMN log_sheet_id DROP NOT NULL;

ALTER TABLE attachments
    ADD COLUMN form_submission_id BIGINT REFERENCES form_submissions (id) ON DELETE CASCADE;

ALTER TABLE attachments
    ADD CONSTRAINT ck_attachments_one_owner
        CHECK ((log_sheet_id IS NOT NULL) <> (form_submission_id IS NOT NULL));

-- Void evidence remains log-sheet-owned: a void cannot name a form attachment.
ALTER TABLE attachments
    ADD CONSTRAINT ck_attachments_void_needs_log_sheet
        CHECK (void_submission_id IS NULL OR log_sheet_id IS NOT NULL);

CREATE INDEX idx_attachments_form_submission_id ON attachments (form_submission_id)
    WHERE form_submission_id IS NOT NULL;
CREATE INDEX idx_attachments_form_field ON attachments (form_submission_id, field_key)
    WHERE form_submission_id IS NOT NULL;


