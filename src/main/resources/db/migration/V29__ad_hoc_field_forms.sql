-- ADMIN DEFINE: whoever may create users (ADMIN today; duplicated ADMIN-like roles inherit).
INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, p.id
FROM role_permissions rp
JOIN permissions seed ON seed.id = rp.permission_id AND seed.code = 'POST:/users'
CROSS JOIN permissions p
WHERE p.code IN (
    'GET:/forms', 'POST:/forms', 'POST:/forms/{id}', 'POST:/forms/{id}/delete',
    'GET:/forms/{id}/fields', 'POST:/forms/{id}/fields',
    'POST:/forms/{id}/fields/{fieldId}', 'POST:/forms/{id}/fields/{fieldId}/delete',
    'POST:/forms/{id}/fields/{fieldId}/state'
)
ON CONFLICT (role_id, permission_id) DO NOTHING;

-- VIEW submissions on the panel: whoever may list log sheets.
INSERT INTO role_permissions (role_id, permission_id)
