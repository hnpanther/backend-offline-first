-- =============================================================================
-- V23 — reference lists on a device: the lease, the download log and the permission
--        (roadmap §31, Phase 2 — «the device lease»)
--
-- WHAT CHANGES.
--   * `lookup_lists.device_lease_hours` — how long a device may keep a list after its LAST
--     successful sync of it. Not counted from login: a tablet that syncs every few minutes never
--     sees it lapse, and one left in a drawer over a weekend loses the list. Expiry deletes the
--     device's copy; nothing an operator recorded is lost with it, because every answer stores
--     its own {code, label} (roadmap §31). 24 hours by default, 1 to 720 allowed.
--   * `lookup_downloads` — one row per page a device fetched: which list, which user, which API
--     session (the `jti`, which names the device's session row), the list's revision, how many
--     items, from which cursor, when (ISO/IEC 27001 A.8.15). If a tablet is lost, what it held is
--     known. It also answers the hard-delete question: an item created after a list's last
--     download never reached a device, so nothing offline can name it.
--   * `GET:/api/lookups/{code}/items` — the device endpoint's permission.
--
-- WHY THE DOWNLOAD LOG RESTRICTS DELETING A LIST. The log is the record of where personal data
-- went; a cascade would erase it with the list. A list a device ever fetched is deactivated, not
-- deleted — the same rule its items already follow. (V22's import history cascades; this does not,
-- and the difference is that import history describes the list, the download log describes the
-- devices.)
--
-- DERIVED GRANT, NOT ROLE CODES. Granted to whoever may already deliver a round from a tablet
-- (`POST:/api/log-sheets/batch`), so a role duplicated from OPERATOR inherits it (docs/security.md
-- §3; same rule as V4, V9, V16). It is a permission of its own, rather than a reuse, because it is
-- a decision of its own: an administrator may withhold personal lists from a role's devices and
-- leave its rounds deliverable — the field then works in code-only mode on that role's tablets.
-- The authority is necessary, never sufficient: the endpoint also requires an open round assigned
-- to the caller that draws from the list (LookupGrantService).
-- =============================================================================

ALTER TABLE lookup_lists
    ADD COLUMN device_lease_hours INTEGER NOT NULL DEFAULT 24;
ALTER TABLE lookup_lists
    ADD CONSTRAINT ck_lookup_lists_device_lease_hours CHECK (device_lease_hours BETWEEN 1 AND 720);

CREATE TABLE lookup_downloads (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id          BIGINT       NOT NULL CONSTRAINT fk_lookup_downloads_list REFERENCES lookup_lists (id),
    user_id          BIGINT       CONSTRAINT fk_lookup_downloads_user REFERENCES users (id),
    session_jti      VARCHAR(64),
    revision         BIGINT       NOT NULL,
    item_count       INTEGER      NOT NULL,
    since_updated_at BIGINT       NOT NULL,
    since_id         BIGINT       NOT NULL,
    fetched_at       BIGINT       NOT NULL,
    CONSTRAINT ck_lookup_downloads_item_count CHECK (item_count >= 0)
);
-- «When did a device last fetch this list» — the hard-delete guard, and the list page.
CREATE INDEX idx_lookup_downloads_list ON lookup_downloads (list_id, fetched_at DESC);
-- «What did this user's devices hold» — the lost-tablet question.
CREATE INDEX idx_lookup_downloads_user ON lookup_downloads (user_id, fetched_at DESC);

INSERT INTO permissions (code, name, category, http_method, endpoint_path) VALUES
('GET:/api/lookups/{code}/items', 'API — دریافت فهرست مرجع روی دستگاه', 'api', 'GET', '/api/lookups/{code}/items');

INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, lists.id
FROM role_permissions rp
JOIN permissions batch ON batch.id = rp.permission_id AND batch.code = 'POST:/api/log-sheets/batch'
CROSS JOIN permissions lists
WHERE lists.code = 'GET:/api/lookups/{code}/items'
ON CONFLICT (role_id, permission_id) DO NOTHING;
