-- Server-owned snapshots advertised to offline clients. Submissions copy the selected
-- snapshot, so later definition edits cannot reinterpret an offline response.
CREATE TABLE form_schema_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_definition_id BIGINT NOT NULL REFERENCES form_definitions(id) ON DELETE CASCADE,
    fields JSONB NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX idx_form_schema_versions_form ON form_schema_versions(form_definition_id, id DESC);
