-- =============================================================================
-- V30 — form submission review (approve / void) + panel FILL authorities
--
-- WHAT. After SUBMITTED, a unit supervisor of the *subject* unit (mirrors log-sheet
-- operational_unit ownership) may APPROVE or VOID. APPROVED withdraws only via
-- unapprove (ADMIN by default, same shape as V8). Panel operators with FILL may
-- draft/submit from the web, not only the tablet.
--
-- VIEW SCOPE (no schema change — behavioural, documented in security.md):
-- list/detail for unit-scoped users keys off subject_unit_id ∈ accessible units
-- (plus author own-work on object-level reads, like log-sheet assignee). Reporter
-- unit alone does NOT grant VIEW. Cross-unit FILL remains.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Status + approval columns
-- -----------------------------------------------------------------------------
ALTER TABLE form_submissions DROP CONSTRAINT IF EXISTS ck_form_submissions_status;
ALTER TABLE form_submissions
    ADD CONSTRAINT ck_form_submissions_status
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'VOIDED'));

ALTER TABLE form_submissions
    ADD COLUMN approved_at BIGINT,
    ADD COLUMN approved_by_user_id BIGINT REFERENCES users (id) ON DELETE RESTRICT;

-- -----------------------------------------------------------------------------
-- 2. Action audit (comment-capable, mirrors log_sheet_action_log shape for review)
-- -----------------------------------------------------------------------------
CREATE TABLE form_submission_action_log (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_submission_id   BIGINT       NOT NULL REFERENCES form_submissions (id) ON DELETE CASCADE,
    action               VARCHAR(30)  NOT NULL,
    source               VARCHAR(20)  NOT NULL,
    actor_user_id        BIGINT       REFERENCES users (id) ON DELETE RESTRICT,
    action_at            BIGINT       NOT NULL,
    recorded_at          BIGINT       NOT NULL,
    comment              VARCHAR(2000),
    CONSTRAINT ck_form_submission_action_log_action
        CHECK (action IN ('APPROVE', 'UNAPPROVE', 'VOID', 'UNVOID'))
);

CREATE INDEX idx_form_submission_action_log_submission
    ON form_submission_action_log (form_submission_id, recorded_at DESC);

-- -----------------------------------------------------------------------------
-- 3. Permissions
-- -----------------------------------------------------------------------------
INSERT INTO permissions (code, name, category, http_method, endpoint_path) VALUES
('POST:/form-submissions/draft',              'ارسال‌های فرم — پیش‌نویس پنل',     'log-sheet', 'POST', '/form-submissions/draft'),
('POST:/form-submissions/submit',             'ارسال‌های فرم — ثبت نهایی پنل',    'log-sheet', 'POST', '/form-submissions/submit'),
('POST:/form-submissions/{id}/approve',       'ارسال‌های فرم — تأیید',            'log-sheet', 'POST', '/form-submissions/{id}/approve'),
('POST:/form-submissions/{id}/unapprove',     'ارسال‌های فرم — لغو تأیید',        'log-sheet', 'POST', '/form-submissions/{id}/unapprove'),
('POST:/form-submissions/{id}/void',          'ارسال‌های فرم — ابطال',            'log-sheet', 'POST', '/form-submissions/{id}/void'),
('POST:/form-submissions/{id}/unvoid',        'ارسال‌های فرم — لغو ابطال',        'log-sheet', 'POST', '/form-submissions/{id}/unvoid');

-- Panel FILL: whoever may draft/submit on the tablet.
INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, p.id
FROM role_permissions rp
JOIN permissions seed ON seed.id = rp.permission_id AND seed.code = 'POST:/api/forms/drafts'
CROSS JOIN permissions p
WHERE p.code IN ('POST:/form-submissions/draft', 'POST:/form-submissions/submit')
ON CONFLICT (role_id, permission_id) DO NOTHING;

-- Approve / void / unvoid: whoever may void a completed log sheet (unit supervisors + admins).
INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, p.id
FROM role_permissions rp
JOIN permissions seed ON seed.id = rp.permission_id AND seed.code = 'POST:/log-sheets/{id}/void'
CROSS JOIN permissions p
WHERE p.code IN (
    'POST:/form-submissions/{id}/approve',
    'POST:/form-submissions/{id}/void',
    'POST:/form-submissions/{id}/unvoid'
)
ON CONFLICT (role_id, permission_id) DO NOTHING;

-- Unapprove: whoever may unapprove a log sheet (ADMIN after V8; not supervisors by default).
INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, p.id
FROM role_permissions rp
JOIN permissions seed ON seed.id = rp.permission_id AND seed.code = 'POST:/log-sheets/{id}/unapprove'
CROSS JOIN permissions p
WHERE p.code = 'POST:/form-submissions/{id}/unapprove'
ON CONFLICT (role_id, permission_id) DO NOTHING;
