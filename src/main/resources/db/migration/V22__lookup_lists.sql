-- =============================================================================
-- V22 — reference data: lookup lists and their items (roadmap §31, Phase 2 — the module)
--
-- WHAT CHANGES.
--   * `lookup_lists`        — a named list (personnel, contractors, violation types …) that
--                             declares its OWN columns in `columns`, so one generic module carries
--                             base data with several fields rather than a table per kind.
--   * `lookup_items`        — one row per entry: a fixed code, a label, the declared columns'
--                             values in `attributes`, an optional parent in another list.
--   * `lookup_list_imports` — one row per applied Excel import: who, when, which file, what it did.
--   * Eight `master-data` permissions for the reference-data pages.
--
-- WHAT DOES NOT CHANGE YET. No form field can point at a list, and no list reaches a tablet:
-- the `lookup` field types, the device lease and the code-only mode are the next phase (roadmap
-- §31, «the device lease»). This migration is only what those will stand on, which is why the
-- columns they need — `revision`, `deactivated_at`, the `offline` flag inside `columns`, the
-- (list, updated_at, id) cursor index — are here now: adding them later to tables that already
-- carry thousands of people costs a rewrite, adding them now costs nothing.
--
-- THE THREE RULES THE SHAPE ENFORCES.
--   1. A code is an identity. Unique per list, case-insensitively, and never changed (the service
--      refuses it; nothing in SQL can say «immutable»). A record that stored `{code, label}` must
--      still mean the same person next year.
--   2. «Delete» is deactivation. `ck_lookup_items_deactivated_at` ties `deactivated_at` to
--      `active`, so the moment an item left service is always known — the rule that will accept an
--      offline record naming an item deactivated after it was filled needs exactly that instant,
--      and `updated_at` moves with every later edit.
--   3. A parent lives in ANOTHER list. `ck_lookup_lists_parent_not_self` refuses a list that is its
--      own parent, and the service refuses a cycle of lists; with both, an item can never be its
--      own ancestor, so no item-level cycle check is needed anywhere.
--
-- WHY `revision` IS A COUNTER ON THE LIST. A device decides whether its copy is behind by comparing
-- one integer, not by walking rows. The application only ever moves it with
-- `UPDATE … SET revision = revision + 1` (the entity maps it read-only), so two administrators
-- editing one list at once cannot lose an increment.
--
-- WHY IMPORT HISTORY CASCADES (AGENTS.md #197, deliberately). A list can only be deleted once it
-- holds no item at all; the history of how a now-empty, now-deleted list was filled describes
-- nothing that still exists. Every other key here is RESTRICT.
--
-- DERIVED GRANTS, NOT ROLE CODES. A list may hold personal data (a personnel list carries names,
-- and may carry a national id), so the pages go to whoever already manages user accounts — holders
-- of `POST:/users`, which is ADMIN alone on the seeded roles — and a role duplicated from one of
-- them inherits it (docs/security.md §3; same rule as V9, V16, V17, V19).
-- =============================================================================

CREATE TABLE lookup_lists (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(50)   NOT NULL,
    name           VARCHAR(255)  NOT NULL,
    description    VARCHAR(1000),
    columns        JSONB         NOT NULL DEFAULT '[]'::jsonb,
    parent_list_id BIGINT CONSTRAINT fk_lookup_lists_parent REFERENCES lookup_lists (id),
    revision       BIGINT        NOT NULL DEFAULT 0,
    active         BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at     BIGINT        NOT NULL,
    updated_at     BIGINT        NOT NULL,
    CONSTRAINT ck_lookup_lists_code_not_blank   CHECK (btrim(code) <> ''),
    CONSTRAINT ck_lookup_lists_name_not_blank   CHECK (btrim(name) <> ''),
    CONSTRAINT ck_lookup_lists_columns_array    CHECK (jsonb_typeof(columns) = 'array'),
    CONSTRAINT ck_lookup_lists_parent_not_self  CHECK (parent_list_id IS NULL OR parent_list_id <> id),
    CONSTRAINT ck_lookup_lists_revision_nonneg  CHECK (revision >= 0)
);

-- Case-insensitive, like every other code in this schema.
CREATE UNIQUE INDEX ux_lookup_lists_code_lower ON lookup_lists (lower(code));
CREATE INDEX idx_lookup_lists_parent_list_id ON lookup_lists (parent_list_id) WHERE parent_list_id IS NOT NULL;

CREATE TABLE lookup_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id        BIGINT        NOT NULL CONSTRAINT fk_lookup_items_list REFERENCES lookup_lists (id),
    code           VARCHAR(100)  NOT NULL,
    label          VARCHAR(255)  NOT NULL,
    attributes     JSONB         NOT NULL DEFAULT '{}'::jsonb,
    parent_item_id BIGINT CONSTRAINT fk_lookup_items_parent REFERENCES lookup_items (id),
    sort_order     INTEGER       NOT NULL DEFAULT 0,
    active         BOOLEAN       NOT NULL DEFAULT TRUE,
    deactivated_at BIGINT,
    anonymised_at  BIGINT,
    search_text    TEXT          NOT NULL DEFAULT '',
    created_at     BIGINT        NOT NULL,
    updated_at     BIGINT        NOT NULL,
    CONSTRAINT ck_lookup_items_code_not_blank   CHECK (btrim(code) <> ''),
    CONSTRAINT ck_lookup_items_label_not_blank  CHECK (btrim(label) <> ''),
    CONSTRAINT ck_lookup_items_attributes_obj   CHECK (jsonb_typeof(attributes) = 'object'),
    CONSTRAINT ck_lookup_items_parent_not_self  CHECK (parent_item_id IS NULL OR parent_item_id <> id),
    CONSTRAINT ck_lookup_items_deactivated_at   CHECK (active = (deactivated_at IS NULL)),
    -- An anonymised item is out of service for good: it stays only so that a code a record
    -- already stored keeps resolving to «this entry existed».
    CONSTRAINT ck_lookup_items_anonymised_inactive CHECK (anonymised_at IS NULL OR NOT active)
);

-- The identity: one code per list, case-insensitively («A12» and «a12» are one person).
CREATE UNIQUE INDEX ux_lookup_items_list_code_lower ON lookup_items (list_id, lower(code));
-- The device sync cursor, half-open over (updated_at, id) — roadmap §31, «How the lists reach the
-- tablet». Also serves «every item of this list» for the import's diff.
CREATE INDEX idx_lookup_items_list_sync ON lookup_items (list_id, updated_at, id);
-- The delete guard's «does any item name this one as its parent».
CREATE INDEX idx_lookup_items_parent_item_id ON lookup_items (parent_item_id) WHERE parent_item_id IS NOT NULL;

CREATE TABLE lookup_list_imports (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id         BIGINT       NOT NULL
                        CONSTRAINT fk_lookup_list_imports_list REFERENCES lookup_lists (id) ON DELETE CASCADE,
    mode            VARCHAR(20)  NOT NULL,
    file_name       VARCHAR(255),
    file_sha256     VARCHAR(64)  NOT NULL,
    rows_read       INTEGER      NOT NULL,
    added           INTEGER      NOT NULL,
    updated         INTEGER      NOT NULL,
    unchanged       INTEGER      NOT NULL,
    deactivated     INTEGER      NOT NULL,
    reactivated     INTEGER      NOT NULL,
    revision_after  BIGINT       NOT NULL,
    actor_user_id   BIGINT       CONSTRAINT fk_lookup_list_imports_actor REFERENCES users (id),
    created_at      BIGINT       NOT NULL,
    CONSTRAINT ck_lookup_list_imports_mode CHECK (mode IN ('ADD_UPDATE', 'FULL_REPLACE'))
);
CREATE INDEX idx_lookup_list_imports_list ON lookup_list_imports (list_id, created_at DESC);

