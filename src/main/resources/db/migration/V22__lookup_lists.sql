INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, p.id
  FROM role_permissions rp
  JOIN permissions src ON src.id = rp.permission_id
                      AND src.code = 'POST:/users'
 CROSS JOIN permissions p
 WHERE p.code IN ('GET:/lookup-lists',
                  'POST:/lookup-lists',
                  'POST:/lookup-lists/{id}',
                  'POST:/lookup-lists/{id}/delete',
                  'POST:/lookup-lists/{id}/items',
                  'POST:/lookup-lists/{id}/items/{itemId}',
                  'POST:/lookup-lists/{id}/items/{itemId}/delete',
                  'POST:/lookup-lists/{id}/import')
ON CONFLICT (role_id, permission_id) DO NOTHING;
