-- =============================================================================
-- TABLE: asset_entries
-- Physical assets (pumps, valves, …) scanned via NFC on the mobile app.
-- Looked up by GET /api/asset-entries/nfc/{nfcTagId}.
--
-- Rules:
--   • asset_code is required and case-insensitive unique.
--   • nfc_tag_id is optional but case-insensitive unique when present
--     (PostgreSQL UNIQUE INDEX allows multiple NULLs).
--   • sub_function_id is required. At most ONE ACTIVE asset per sub-function
--     (ux_asset_entries_active_sub_function, a PARTIAL unique index on `WHERE active`);
--     any number of INACTIVE assets may share the same sub-function. This models
--     equipment replacement: a broken pump is deactivated and kept for history while
--     its successor is attached to the very same sub-function.
--   • class_id selects the field schema for log-sheet generation.
--   • active=false keeps the row findable by NFC/sync but excludes the asset from
--     new log-sheet preview/generation scope queries. Deactivating an asset also
--     RELEASES an nfc_tag_id that was inherited from the sub-function (equal to its
--     tag or code) by clearing it — otherwise the successor asset, which inherits the
--     same value, would collide on ux_asset_entries_nfc_tag_id_lower. A tag the asset
--     owns in its own right (any other value) is kept: it is physically on that asset.
--   • status is a free-form, schema-only field for the asset's real-world operational
--     state (e.g. ON / OFF / IDLE / MAINTENANCE) — NOT the same concept as active.
--     No entity field, DTO, API, or UI reads/writes it yet; deliberately left without
--     a CHECK constraint or enum since the exact set of states isn't finalized.
--     locations / plant_systems / main_functions / sub_functions carry the same
--     schema-only `status` column, for the same reason.
--   • asset_name_fa is a reserved secondary (Persian) title, schema-only for now — the
--     same column exists as name_fa on the four hierarchy tables.
-- =============================================================================
CREATE TABLE asset_entries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code      VARCHAR(255) NOT NULL,
    nfc_tag_id      VARCHAR(255),
    -- Physical NFC chip serial / UID, e.g. "00:aa:34:9f:12:cd". Optional, but unique when
    -- supplied (ux_asset_entries_nfc_serial_lower). NOT the same thing as nfc_tag_id: the tag id
    -- is the LOGICAL lookup key and is inherited from the sub-function's tag when the asset has
    -- none of its own (and released again when the asset is deactivated), while this identifies
    -- the piece of hardware and is never inherited, derived, or released.
    nfc_serial      VARCHAR(255),
    class_id        BIGINT,
    asset_name      VARCHAR(255),
    asset_name_fa   VARCHAR(255),
    sub_function_id BIGINT       NOT NULL,
    description     VARCHAR(500),
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    status          VARCHAR(30),
    created_at      BIGINT,
    updated_at      BIGINT
);

-- =============================================================================
-- TABLE: log_sheet_templates
-- Reusable definitions for generating round log sheets (manual or scheduled).
-- asset_selection_mode decides how a generated sheet's assets are chosen:
--   SCOPE    (default) — re-resolved on EVERY generation from scope_type + scope_id +
--                        class_id, so assets added to that scope later are picked up
--                        automatically.
--   EXPLICIT           — a FROZEN, hand-picked set stored in log_sheet_template_assets;
--                        the scope/class columns are not used to select assets. The list
--                        never changes on its own; the only filter applied at generation
--                        time is that inactive assets are skipped. This is the
--                        "custom log sheet, but scheduled" mode, so its assets may span
--                        several asset classes and class_id may be NULL.
--
-- Scope (scope_type + scope_id) selects a subtree of the asset hierarchy;
-- class_id filters which assets of that scope are included (SCOPE mode only).
-- operational_unit_id scopes who may manage/generate from this template, and is
-- copied onto every generated log_sheets row — it is the ONLY thing that decides
-- which unit sees/fills the resulting work.
--
-- restrict_scope_to_unit controls scope picking, not access:
--   TRUE  (default) — the scope must sit under a location owned by that unit;
--                     the pickers only offer that unit's hierarchy.
--   FALSE           — the scope may be anywhere in the plant. Used when a unit is
--                     deliberately made responsible for assets outside its own
--                     locations. Access is unaffected: the assigned unit still
--                     reaches the work through log_sheets.operational_unit_id, and
--                     no other unit gains visibility of those assets.
--
-- Scheduling (when generation_mode is schedule-driven):
--   recurrence_unit / recurrence_every / schedule_start_at / schedule_active /
--   next_run_at / last_run_at / completion_window_minutes.
-- name is case-insensitive unique. active=false disables generation.
-- =============================================================================
CREATE TABLE log_sheet_templates (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                      VARCHAR(255) NOT NULL,
    description               VARCHAR(255),
    scope_type                VARCHAR(255),
    scope_id                  BIGINT,
    -- Required for SCOPE mode; NULL is allowed for EXPLICIT templates, whose hand-picked
    -- assets may span several classes (like a custom log sheet).
    class_id                  BIGINT,
    asset_selection_mode      VARCHAR(20)  NOT NULL DEFAULT 'SCOPE',
    operational_unit_id       BIGINT,
    restrict_scope_to_unit    BOOLEAN      NOT NULL DEFAULT TRUE,
    generation_mode           VARCHAR(20)  NOT NULL DEFAULT 'MANUAL',
    recurrence_unit           VARCHAR(20),
    recurrence_every          INTEGER,
    schedule_start_at         BIGINT,
    schedule_active           BOOLEAN      NOT NULL DEFAULT FALSE,
    next_run_at               BIGINT,
    last_run_at               BIGINT,
    completion_window_minutes INTEGER,
    active                    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at                BIGINT,
    updated_at                BIGINT
);

-- =============================================================================
-- TABLE: log_sheet_template_assets
-- The frozen asset set of an EXPLICIT template (ignored by SCOPE templates).
-- Composite PK (template_id, asset_id). The template side CASCADEs — the list is
-- meaningless without its template and is always rewritten wholesale on save. The
-- asset side RESTRICTs so an asset referenced by a template cannot be hard-deleted
-- (deactivate it instead: generation already skips inactive assets).
-- =============================================================================
CREATE TABLE log_sheet_template_assets (
    template_id BIGINT NOT NULL,
    asset_id    BIGINT NOT NULL,
    PRIMARY KEY (template_id, asset_id)
);

-- =============================================================================
-- TABLE: log_sheets
