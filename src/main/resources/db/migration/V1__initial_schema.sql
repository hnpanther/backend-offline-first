-- =============================================================================
CREATE TABLE log_sheet_void_submissions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_sheet_id         BIGINT NOT NULL,
    submitted_by_user_id BIGINT,
    completed_at         BIGINT,
    synced_at            BIGINT,
    reason               VARCHAR(255),
    payload              JSONB
);

-- =============================================================================
-- TABLE: nfc_fault_reports
-- One row per reported NFC scan failure for a (log_sheet_id, asset_id) pair:
-- lets an operator or supervisor record that an asset's tag could not be scanned
-- (missing, broken, or the device's own NFC hardware is unusable), which unlocks
-- a manual-entry fallback for that one asset within that one log sheet. Multiple
-- reports for the same pair are allowed (no unique constraint) — the unlock rule
-- is simply "at least one report exists", not "exactly one". Insert-only (never
-- edited or deleted except by ADMIN) — same audit philosophy as
-- log_sheet_void_submissions. status exists for future workflow states (e.g.
-- under review / resolved) but only 'OPEN' is used today. operational_unit_id is
-- denormalized from the log sheet at creation time for cheap unit-scoped listing
-- without a join. Cascades with the parent sheet.
-- =============================================================================
CREATE TABLE nfc_fault_reports (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_sheet_id         BIGINT       NOT NULL,
    asset_id             BIGINT       NOT NULL,
    operational_unit_id  BIGINT,
    reported_by_user_id  BIGINT,
    reported_by_name     VARCHAR(255),
    source               VARCHAR(20)  NOT NULL,
    reason               VARCHAR(2000),
    status               VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
    created_at           BIGINT       NOT NULL,
    synced_at            BIGINT,
    client_action_id     VARCHAR(255),
    local_id             VARCHAR(255),
    CONSTRAINT uk_nfc_fault_reports_client_action_id UNIQUE (client_action_id)
);

-- =============================================================================
-- TABLE: audit_log
-- Generic field-level change history for master and operational entities.
-- Written by RepositoryAuditAspect (async). changes is JSONB array of
-- {field, oldValue, newValue}. actor_user_id FK RESTRICT (users with audit
-- history cannot be hard-deleted).
-- Indexed for retention purge (recorded_at) and entity drill-down.
-- =============================================================================
CREATE TABLE audit_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type     VARCHAR(100) NOT NULL,
    entity_id       VARCHAR(255),
    action          VARCHAR(20)  NOT NULL,
    actor_user_id   BIGINT,
    actor_username  VARCHAR(255),
    source          VARCHAR(20),
    request_id      VARCHAR(64),
    changes         JSONB,
    recorded_at     BIGINT       NOT NULL
);

-- =============================================================================
-- TABLE: import_jobs
-- Async batch Excel import jobs (admin Batch Import UI).
-- The uploaded file is stored on disk under app.import.storage-path while the job
-- is PENDING/RUNNING; deleted when the job finishes (or rejected early).
-- Progress counters and status drive the polling UI.
--
-- Columns:
--   job_uuid             Public UUID for API/UI (UNIQUE).
--   entity_type          Which importer to run (locations, assets, users, …).
--   status               PENDING | RUNNING | COMPLETED | FAILED | CANCELLED.
--   file_*               Original name, absolute path, size.
--   total_rows / processed_rows / success_count / error_count  Progress.
--   submitted_by_user_id Who started the job (FK RESTRICT).
-- =============================================================================
CREATE TABLE import_jobs (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_uuid             VARCHAR(36)   NOT NULL,
    entity_type          VARCHAR(64)   NOT NULL,
    status               VARCHAR(32)   NOT NULL,
    file_name            VARCHAR(512)  NOT NULL,
    file_path            VARCHAR(1024) NOT NULL,
    file_size            BIGINT        NOT NULL DEFAULT 0,
    total_rows           INT           NOT NULL DEFAULT 0,
    processed_rows       INT           NOT NULL DEFAULT 0,
    success_count        INT           NOT NULL DEFAULT 0,
    error_count          INT           NOT NULL DEFAULT 0,
    submitted_by_user_id BIGINT        NOT NULL,
    error_message        TEXT,
    created_at           BIGINT        NOT NULL,
    started_at           BIGINT,
    completed_at         BIGINT,
    CONSTRAINT uk_import_jobs_uuid UNIQUE (job_uuid)
);

-- =============================================================================
