-- =============================================================================
CREATE TABLE asset_classes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    created_at BIGINT,
    updated_at BIGINT
);

-- =============================================================================
-- TABLE: field_definitions
-- Dynamic form fields for one asset class (temperature, pressure, options, …).
-- Used when validating log-sheet entry form_data and when building mobile bundles.
