-- =============================================================================
-- TABLE: locations
-- Hierarchical site / area / room master data under the asset plant hierarchy.
-- parent_id forms a location tree (ON DELETE RESTRICT — delete children first).
-- code is case-insensitive unique (ux_locations_code_lower).
--
-- Responsible operational units live in the location_units join table below — a
-- location can be owned by SEVERAL units (mirrors how one unit has several
-- supervisors/operators). There is deliberately no unit_id column here.
-- =============================================================================
CREATE TABLE locations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(255) NOT NULL,
    name       VARCHAR(255),
    name_fa    VARCHAR(255),
    parent_id  BIGINT,
    status     VARCHAR(30),
    created_at BIGINT,
    updated_at BIGINT
);

-- =============================================================================
-- TABLE: location_units
-- Many-to-many: which operational units are responsible for which locations.
-- Composite PK (location_id, unit_id); same shape as unit_supervisors /
-- unit_operators. This is the root of every unit-scope walk:
--   unit → location_units → location tree → systems → main/sub functions → assets
-- (see AssetUnitScopeSql.SCOPED_SUBFUNCTIONS_CTE).
--
-- A location with no row here belongs to no unit and is therefore invisible to
-- unit-scoped roles — only ADMIN / HIGH_USER see it.
-- =============================================================================
CREATE TABLE location_units (
    location_id BIGINT NOT NULL,
    unit_id     BIGINT NOT NULL,
    PRIMARY KEY (location_id, unit_id)
);

-- =============================================================================
-- TABLE: plant_systems
-- Physical or logical plant systems hanging under a location (and optionally
-- nested under a parent plant system). Part of log-sheet template scope trees.
-- code is case-insensitive unique; name is required.
-- =============================================================================
CREATE TABLE plant_systems (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(255) NOT NULL,
    name        VARCHAR(255) NOT NULL,
    name_fa     VARCHAR(255),
    parent_id   BIGINT,
    location_id BIGINT,
    status      VARCHAR(30),
    created_at  BIGINT,
    updated_at  BIGINT
);

-- =============================================================================
-- TABLE: main_functions
-- Functional groupings that may hang under a plant system, another main function,
-- or directly under a location. Used when resolving which sub-functions (and thus
-- assets) fall inside a log-sheet template scope.
-- code is case-insensitive unique; name is required.
-- =============================================================================
CREATE TABLE main_functions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(255) NOT NULL,
    name        VARCHAR(255) NOT NULL,
    name_fa     VARCHAR(255),
    parent_id   BIGINT,
    system_id   BIGINT,
    location_id BIGINT,
    status      VARCHAR(30),
    created_at  BIGINT,
    updated_at  BIGINT
);

-- =============================================================================
-- TABLE: sub_functions
-- Leaf (or nested) equipment / function nodes. Assets attach here via
-- asset_entries.sub_function_id (exactly one asset per sub-function — unique index).
-- When an asset NFC is blank, the app may copy tag (or code) as the NFC value.
--
-- Parentage: parent_id (nested sub-function), and/or main_function_id, system_id,
-- location_id depending on where the node is attached in the hierarchy.
--
-- Uniqueness: code and tag are each case-insensitive unique globally.
-- =============================================================================
CREATE TABLE sub_functions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(255) NOT NULL,
    name             VARCHAR(255),
    name_fa          VARCHAR(255),
    tag              VARCHAR(255) NOT NULL,
    parent_id        BIGINT,
    main_function_id BIGINT,
    system_id        BIGINT,
    location_id      BIGINT,
    status           VARCHAR(30),
    created_at       BIGINT,
    updated_at       BIGINT
);

-- =============================================================================
-- TABLE: asset_classes
-- Asset type / form schema container. name is case-insensitive unique.
