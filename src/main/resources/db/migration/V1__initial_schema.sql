    template_id         BIGINT,
    template_name       VARCHAR(255),
    scope_summary       VARCHAR(255),
    operational_unit_id BIGINT,
    status              VARCHAR(30)  NOT NULL DEFAULT 'PENDING',
    origin              VARCHAR(20)  NOT NULL DEFAULT 'MANUAL',
    assignee_user_id    BIGINT,
    assignment_type     VARCHAR(30),
    assigned_by_user_id BIGINT,
    completed_by_user_id BIGINT,
    operator_name       VARCHAR(255),
    notes               VARCHAR(4000),
    due_at              BIGINT,
    assigned_at         BIGINT,
    claimed_at          BIGINT,
    started_at          BIGINT,
    completed_at        BIGINT,
    expired_at          BIGINT,
    cancelled_at        BIGINT,
    submitted_at        BIGINT,
    synced_at           BIGINT,
    draft_saved_at      BIGINT,
    sync_status         VARCHAR(255),
    field_definitions_snapshot JSONB,
    created_at          BIGINT,
    updated_at          BIGINT
);

-- =============================================================================
-- TABLE: log_sheet_entries
-- One row per asset included in a generated log sheet.
-- form_data JSONB holds operator measurements keyed by field_definitions.field_key.
-- Denormalized asset_name / nfc_tag_id / sub_function_code / sub_function_tag /
-- class_id snapshot identity for display and offline use.
-- Deleted with the parent sheet (ON DELETE CASCADE).
-- Asset FK is RESTRICT so assets referenced by historical sheets cannot be hard-deleted.
--
-- entry_source / filled_by_user_id record how and by whom this specific entry was
-- actually filled (web / PWA+NFC scan / PWA manual) — stamped server-side on submit,
-- and only re-stamped when the incoming form_data actually changed from what's
-- already stored (see LogSheetService gotcha on reassignment attribution leaks).
-- =============================================================================
CREATE TABLE log_sheet_entries (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_sheet_id       BIGINT,
    asset_id           BIGINT,
    asset_name         VARCHAR(255),
    nfc_tag_id         VARCHAR(255),
    -- Snapshot of the asset's physical chip serial at generation time. Deliberately NOT unique:
    -- every generated sheet copies the same asset's serial, and the snapshot must survive the
    -- asset row being edited or deleted. Carried to the PWA in LogSheetEntryDto so an offline
    -- scan can match the chip UID without a round trip.
    nfc_serial         VARCHAR(255),
    sub_function_code  VARCHAR(255),
    sub_function_tag   VARCHAR(255),
    class_id           BIGINT,
    form_data          JSONB,
    entry_source       VARCHAR(20),
    filled_by_user_id  BIGINT,
    created_at         BIGINT,
    updated_at         BIGINT
);

-- =============================================================================
-- TABLE: log_sheet_action_log
-- Immutable lifecycle audit for a log sheet: claim, assign, reassign, release,
-- extend, takeover, complete, etc.
--
-- Columns:
--   action_at         Device / real-world event time.
--   recorded_at       Server persist time.
--   client_action_id  Idempotency key when the same offline action is replayed
--                     on sync (UNIQUE when set).
--   actor / from / to user FKs describe who performed or received the action.
-- Cascades when the parent log_sheet is deleted.
-- =============================================================================
CREATE TABLE log_sheet_action_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_sheet_id     BIGINT       NOT NULL,
    action           VARCHAR(30)  NOT NULL,
    actor_user_id    BIGINT,
    from_user_id     BIGINT,
    to_user_id       BIGINT,
    source           VARCHAR(20),
    action_at        BIGINT       NOT NULL,
    recorded_at      BIGINT       NOT NULL,
    client_action_id VARCHAR(255),
    -- Optional free-text reason the actor gave ("why", not "what"). Always optional — the action
    -- succeeds with this left null. Supplied today by EXTEND / CANCEL / VOID / UNVOID /
    -- ADMIN_REOPEN from the web panel; the column itself is action-agnostic.
    comment          VARCHAR(1000),
    CONSTRAINT uk_lsal_client_action_id UNIQUE (client_action_id)
);

-- =============================================================================
-- TABLE: log_sheet_void_submissions
-- Late offline operator completions that arrived after another actor already
