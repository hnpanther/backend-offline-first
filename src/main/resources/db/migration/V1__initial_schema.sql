    user_id BIGINT NOT NULL,
    PRIMARY KEY (unit_id, user_id)
);

-- =============================================================================
-- TABLE: unit_operators
-- Many-to-many: which users operate within which operational units.
-- Same shape as unit_supervisors; drives operator inbox / claim eligibility.
-- =============================================================================
CREATE TABLE unit_operators (
