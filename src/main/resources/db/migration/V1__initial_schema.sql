-- =============================================================================
-- backend-offline-first — consolidated schema (V1)
--
-- Single Flyway migration for a fresh database. Covers:
--   • Identity & RBAC (users, roles, permissions, unit staff links)
--   • Mobile-API session registry (api_sessions) for revocable, single-session JWTs
--   • Asset hierarchy master data (locations → systems → main/sub functions)
--   • Asset classes, field definitions, and physical asset entries
--   • Operational work: log-sheet templates, sheets, entries, action audit, void submissions
--     (including the CANCELLED lifecycle status — cancelled_at column)
--   • NFC fault reports (nfc_fault_reports) — unlocks per-asset manual entry when a tag
--     is broken/missing; log_sheet_entries.entry_source / filled_by_user_id record how
--     and by whom each entry was actually filled
--   • Asset operational status (asset_entries.status) — schema-only placeholder for a
--     future ON/OFF/IDLE/MAINTENANCE-style field, distinct from the active flag
--   • Uniqueness on user contact fields (national_code, phone_number, nfc_tag_id) —
--     each must be blank or unique, same convention as other business keys
--   • Generic entity audit_log and async Excel import_jobs
--   • Ops/monitoring, web-session, and login-attempt admin permissions
--
-- Conventions:
--   • Primary keys are BIGINT GENERATED BY DEFAULT AS IDENTITY.
--   • Business / natural keys remain VARCHAR (code, username, local_id, nfc_tag_id, …).
--   • Timestamps are epoch millis (BIGINT), not TIMESTAMP columns.
--   • Case-insensitive uniqueness for master codes/tags/names uses UNIQUE INDEX on LOWER(…).
--   • Foreign keys default to ON DELETE RESTRICT so parents with dependents cannot be removed.
--     Cascades are used only for child rows that are meaningless without the parent
--     (log_sheet_entries, log_sheet_action_log, log_sheet_void_submissions, import_job_errors).
--   • Permission model: one permissions row per HTTP endpoint; code = METHOD:path.
-- =============================================================================

-- =============================================================================
-- TABLE: users
-- Application accounts for the admin web UI and mobile field operators.
-- Hard-delete is blocked in application logic (and by FKs) once the user has
-- participated in log sheets, audits, or imports; prefer setting active=false.
--
-- Columns:
--   username        Unique login name (exact match; application may trim).
--   password_hash   Encoded credential for LOCAL / HYBRID users.
--   auth_type       LOCAL | ACTIVE_DIRECTORY | HYBRID (CHECK constraint).
--   full_name       Display name (optional).
--   national_code   Optional national ID (max 15); blank or unique (ux_users_national_code).
--   phone_number    Optional phone (max 15); blank or unique (ux_users_phone_number).
--   nfc_tag_id      Optional NFC identifier for the person (max 50); blank or unique,
--                   case-insensitive (ux_users_nfc_tag_id_lower).
--   active          Soft enable/disable flag; inactive users cannot authenticate.
--   created_at / updated_at  Epoch millis.
-- =============================================================================
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    auth_type     VARCHAR(32)  NOT NULL DEFAULT 'LOCAL',
    full_name     VARCHAR(255),
    national_code VARCHAR(15),
    phone_number  VARCHAR(15),
    nfc_tag_id    VARCHAR(50),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    BIGINT,
    updated_at    BIGINT,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT ck_users_auth_type CHECK (auth_type IN ('LOCAL', 'ACTIVE_DIRECTORY', 'HYBRID'))
);

-- =============================================================================
-- TABLE: operational_units
-- Hierarchical organization tree (plant / department / shift areas).
-- Used to scope which locations, templates, and log sheets a unit-scoped role
-- (SUPERVISOR / OPERATOR / SENIOR_OPERATOR) may see or manage.
--
-- Columns:
--   code       Business code; case-insensitive unique via ux_operational_units_code_lower.
--   name       Display name.
--   parent_id  Self-FK to another unit (NULL = root). ON DELETE RESTRICT.
-- =============================================================================
CREATE TABLE operational_units (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(255) NOT NULL,
    name       VARCHAR(255),
    parent_id  BIGINT,
    created_at BIGINT,
    updated_at BIGINT
);

-- =============================================================================
