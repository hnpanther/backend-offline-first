);

-- =============================================================================
-- TABLE: api_sessions
-- Server-side registry of issued mobile-API JWTs (stateful control on top of an
-- otherwise-stateless token): every issued token is recorded by its `jti` claim,
-- an administrator can list devices and revoke individual sessions, and a user
-- may hold at most ONE active session (logging in on a second device supersedes
-- the first — enforced in ApiSessionService). Token lifetime itself lives in
-- app_settings ('auth.jwt.expiry_minutes'). Rows are kept after revocation/expiry
-- so the admin panel can show login history; JwtAuthenticationFilter treats a
-- token as valid only while the matching row has revoked_at IS NULL and
-- expires_at > now.
--
-- Columns:
--   jti           Unique token id (JWT "jti" claim) — the lookup key per request.
--   device_label  Client-supplied device name (optional; from the login payload).
--   user_agent    Raw User-Agent header, truncated — helps identify the tablet.
--   revoke_reason ADMIN | SUPERSEDED (new login on another device) | LOGOUT.
-- =============================================================================
CREATE TABLE api_sessions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti           VARCHAR(64)  NOT NULL,
    user_id       BIGINT       NOT NULL,
    username      VARCHAR(255),
    device_label  VARCHAR(255),
    user_agent    VARCHAR(512),
    ip_address    VARCHAR(64),
    issued_at     BIGINT       NOT NULL,
    expires_at    BIGINT       NOT NULL,
    last_seen_at  BIGINT,
    revoked_at    BIGINT,
    revoked_by    BIGINT,
    revoke_reason VARCHAR(32),
    CONSTRAINT uk_api_sessions_jti UNIQUE (jti)
);

-- =============================================================================
-- TABLE: permissions
-- Atomic access rights for Spring Security @PreAuthorize checks.
-- One row per HTTP endpoint; code format is METHOD:path (e.g. GET:/users).
-- Seeded later in this migration; assigned to roles via role_permissions.
--
-- Columns:
--   code           Unique permission key (METHOD:path).
--   name           Persian (or UI) label for admin role editor.
--   category       Grouping: general | admin | organization | master-data |
--                  operational | reports | api.
--   http_method    GET / POST / … (informational; mirrors code).
--   endpoint_path  Path pattern as used by the web/API layer.
-- =============================================================================
CREATE TABLE permissions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(255) NOT NULL,
    name          VARCHAR(255),
    category      VARCHAR(255),
    http_method   VARCHAR(10),
    endpoint_path VARCHAR(512),
    CONSTRAINT uk_permissions_code UNIQUE (code)
);

-- =============================================================================
-- TABLE: roles
