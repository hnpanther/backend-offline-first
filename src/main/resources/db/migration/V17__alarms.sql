-- =============================================================================
-- V17 — alarms: a reading that needs a person, not only a row in a report
--
-- WHAT THIS ADDS. Five tables and eight permissions. Nothing existing is altered.
--
--   alarm_rules                — the RATIONALISATION: which parameter raises an alarm, at what
--                                severity, after how many consecutive readings, and what the
--                                supervisor is expected to do about it. One rule per field
--                                definition. A parameter with no rule never raises an alarm.
--   alarms                     — one row per CONDITION (asset × rule), with a lifecycle:
--                                OPEN → ACKNOWLEDGED → CLOSED. Repeated readings of the same
--                                condition update this row; they never add a second one.
--   alarm_events               — the append-only timeline of each alarm.
--   alarm_evaluation_requests  — a durable queue: «this round changed, re-judge its assets».
--   alarm_webhook_deliveries   — the outbox: one row per event to POST to the configured URL.
--
-- WHY A QUEUE BETWEEN A ROUND AND ITS ALARMS. The rounds that raise alarms are written by the
-- completion paths — a tablet delivering a finished round, the web fill page completing one.
-- Those transactions must NEVER fail because of alarm bookkeeping: an operator's delivered work
-- outranks a notification about it. Evaluating inline would put a unique-index race, a lock wait
-- or a bug in the alarm code inside the operator's transaction. So the completion path does one
-- thing — inserts a row here, which cannot conflict with anything — and the evaluation runs
-- after commit, in its own transaction, and is retried if it fails. Evaluation is a pure
-- recomputation from the stored readings, so running it twice, late or out of order gives the
-- same answer.
--
-- WHY THE WEBHOOK IS AN OUTBOX. roadmap §11: a delivery row is written in the SAME transaction
-- as the alarm it announces, so «the alarm exists» and «it will be announced» cannot disagree;
-- a scheduler POSTs it afterwards, with backoff, a give-up, and nothing ever called from inside
-- a transaction. The URL and key are configuration (app.alarm.webhook.*), never data: an
-- admin-editable outbound URL is a way to point the server at an internal address.
--
-- NO FOREIGN KEY TO users, deliberately and on every actor column here. The same decision as
-- audit_log (V3 §5, AuditTrailOutlivesUserIntegrationTest): an alarm acknowledged by somebody who
-- later leaves must keep its history, and a RESTRICT key would turn «delete this user» into
-- «first find every alarm they ever touched». The ids are resolved best-effort when displayed.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. alarm_rules — which parameter is worth a person's attention
--
-- Keyed by FIELD DEFINITION, not by field key: a key is unique within a class, not across
-- classes, and a sub-class may redefine a parent's key (V5). A definition inherited by a
-- sub-class keeps its id through flattening (AssetFieldResolver.copyOf), so a rule on a parent
-- class's field applies to the sub-class's assets too, which is what «this kind of pump» means.
--
-- ON DELETE CASCADE from field_definitions: a field can only be hard-deleted while nothing
-- names its key (roadmap §23), and an alarm implies a reading that names it — so a rule with
-- alarms can never be cascaded away, and a rule with none goes with its field.
-- -----------------------------------------------------------------------------
CREATE TABLE alarm_rules (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_definition_id   BIGINT        NOT NULL,
    trigger_severity      VARCHAR(10)   NOT NULL,
    consecutive_readings  INTEGER       NOT NULL DEFAULT 1,
    clear_after_readings  INTEGER       NOT NULL DEFAULT 1,
    window_days           INTEGER,
    priority              VARCHAR(10)   NOT NULL DEFAULT 'MEDIUM',
    expected_action       VARCHAR(1000) NOT NULL,
    active                BOOLEAN       NOT NULL DEFAULT TRUE,
    created_by_user_id    BIGINT,
    updated_by_user_id    BIGINT,
    created_at            BIGINT        NOT NULL,
    updated_at            BIGINT        NOT NULL,
    CONSTRAINT uq_alarm_rules_field UNIQUE (field_definition_id),
    CONSTRAINT fk_alarm_rules_field FOREIGN KEY (field_definition_id)
        REFERENCES field_definitions (id) ON DELETE CASCADE,
    CONSTRAINT ck_alarm_rules_trigger CHECK (trigger_severity IN ('WARNING', 'DANGER')),
    CONSTRAINT ck_alarm_rules_consecutive CHECK (consecutive_readings BETWEEN 1 AND 20),
    CONSTRAINT ck_alarm_rules_clear_after CHECK (clear_after_readings BETWEEN 1 AND 20),
    CONSTRAINT ck_alarm_rules_window CHECK (window_days IS NULL OR window_days BETWEEN 1 AND 365),
    CONSTRAINT ck_alarm_rules_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_alarm_rules_action CHECK (length(btrim(expected_action)) > 0)
);

COMMENT ON TABLE alarm_rules IS
    'Which field definition raises an alarm, at what severity, after how many consecutive '
    'readings, and what the supervisor is expected to do (V17).';


-- -----------------------------------------------------------------------------
-- 2. alarms — one row per condition, with a lifecycle
--
-- THE ONE-LIVE-ALARM INDEX is the dedupe. A pump reading high on five rounds in a row is ONE
-- alarm with occurrence_count = 5, not five rows and five notifications. Partial, so a closed
-- alarm does not stop the same condition being raised again later.
--
-- The rule's parameters are FROZEN onto the alarm (trigger, consecutive, clear-after): editing
-- a rule describes the alarms it will raise, not the ones already in a supervisor's queue.
-- -----------------------------------------------------------------------------
CREATE TABLE alarms (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_rule_id           BIGINT        NOT NULL,
    asset_id                BIGINT        NOT NULL,
    field_definition_id     BIGINT,
    field_key               VARCHAR(255)  NOT NULL,
    field_label             VARCHAR(255),
    field_unit              VARCHAR(100),
    asset_name              VARCHAR(255),
    operational_unit_id     BIGINT,
    log_sheet_id            BIGINT,
    state                   VARCHAR(20)   NOT NULL,
    severity                VARCHAR(10)   NOT NULL,
    priority                VARCHAR(10)   NOT NULL,
    trigger_severity        VARCHAR(10)   NOT NULL,
    consecutive_readings    INTEGER       NOT NULL,
    clear_after_readings    INTEGER       NOT NULL,
    expected_action         VARCHAR(1000),
    occurrence_count        INTEGER       NOT NULL,
    condition_met_at        BIGINT        NOT NULL,
    first_reading_at        BIGINT        NOT NULL,
    last_reading_at         BIGINT        NOT NULL,
    last_value              VARCHAR(1000),
    returned_to_normal_at   BIGINT,
    acknowledged_by_user_id BIGINT,
    acknowledged_at         BIGINT,
    ack_comment             VARCHAR(1000),
    closed_by_user_id       BIGINT,
    closed_at               BIGINT,
    close_reason            VARCHAR(30),
    close_comment           VARCHAR(1000),
    created_at              BIGINT        NOT NULL,
    updated_at              BIGINT        NOT NULL,
    version                 BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_alarms_rule FOREIGN KEY (alarm_rule_id)
        REFERENCES alarm_rules (id) ON DELETE RESTRICT,
    CONSTRAINT fk_alarms_asset FOREIGN KEY (asset_id)
        REFERENCES asset_entries (id) ON DELETE CASCADE,
    CONSTRAINT fk_alarms_unit FOREIGN KEY (operational_unit_id)
        REFERENCES operational_units (id) ON DELETE SET NULL,
    CONSTRAINT fk_alarms_log_sheet FOREIGN KEY (log_sheet_id)
        REFERENCES log_sheets (id) ON DELETE SET NULL,
    CONSTRAINT ck_alarms_state CHECK (state IN ('OPEN', 'ACKNOWLEDGED', 'CLOSED')),
    CONSTRAINT ck_alarms_severity CHECK (severity IN ('WARNING', 'DANGER')),
    CONSTRAINT ck_alarms_trigger CHECK (trigger_severity IN ('WARNING', 'DANGER')),
    CONSTRAINT ck_alarms_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_alarms_occurrences CHECK (occurrence_count >= 1),
    -- A closed alarm says why; a live one has no reason to give.
    CONSTRAINT ck_alarms_closed_has_reason CHECK (
        (state = 'CLOSED' AND close_reason IS NOT NULL AND closed_at IS NOT NULL)
        OR (state <> 'CLOSED' AND close_reason IS NULL AND closed_at IS NULL))
);

CREATE UNIQUE INDEX ux_alarms_one_live_per_rule_and_asset
    ON alarms (alarm_rule_id, asset_id) WHERE state <> 'CLOSED';
-- The supervisor's queue and the dashboard card: live alarms of the units in scope.
CREATE INDEX idx_alarms_unit_state ON alarms (operational_unit_id, state);
-- «Which readings has a closed alarm already consumed» — the evaluation's watermark lookup.
CREATE INDEX idx_alarms_rule_asset_last_reading ON alarms (alarm_rule_id, asset_id, last_reading_at);

COMMENT ON TABLE alarms IS
    'One row per alarm condition (asset x rule), OPEN -> ACKNOWLEDGED -> CLOSED. Repeated '
    'breaching readings update the live row; they never add a second one (V17).';


-- -----------------------------------------------------------------------------
-- 3. alarm_events — the timeline
-- -----------------------------------------------------------------------------
CREATE TABLE alarm_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_id        BIGINT        NOT NULL,
    event_type      VARCHAR(30)   NOT NULL,
    occurred_at     BIGINT        NOT NULL,
    actor_user_id   BIGINT,
    log_sheet_id    BIGINT,
    severity        VARCHAR(10),
    value_text      VARCHAR(1000),
    comment         VARCHAR(1000),
    CONSTRAINT fk_alarm_events_alarm FOREIGN KEY (alarm_id)
        REFERENCES alarms (id) ON DELETE CASCADE,
    CONSTRAINT fk_alarm_events_log_sheet FOREIGN KEY (log_sheet_id)
        REFERENCES log_sheets (id) ON DELETE SET NULL
);

CREATE INDEX idx_alarm_events_alarm ON alarm_events (alarm_id, occurred_at);


-- -----------------------------------------------------------------------------
-- 4. alarm_evaluation_requests — «re-judge this round's assets»
--
-- No unique key on log_sheet_id: two requests for one round are harmless (evaluation is a
-- recomputation) and a unique key would be the one thing in the completion transaction that
-- could fail. CASCADE from log_sheets so deleting a round never waits on its pending request.
-- -----------------------------------------------------------------------------
CREATE TABLE alarm_evaluation_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_sheet_id     BIGINT        NOT NULL,
    reason           VARCHAR(30)   NOT NULL,
    attempts         INTEGER       NOT NULL DEFAULT 0,
    next_attempt_at  BIGINT        NOT NULL,
    last_error       VARCHAR(1000),
    created_at       BIGINT        NOT NULL,
    CONSTRAINT fk_alarm_eval_log_sheet FOREIGN KEY (log_sheet_id)
        REFERENCES log_sheets (id) ON DELETE CASCADE
);

CREATE INDEX idx_alarm_eval_due ON alarm_evaluation_requests (next_attempt_at, id);


-- -----------------------------------------------------------------------------
-- 5. alarm_webhook_deliveries — the outbox
--
-- payload is TEXT, not jsonb: the receiver is promised the exact bytes, and jsonb would
-- re-order keys and normalise numbers between the write and the POST.
-- -----------------------------------------------------------------------------
CREATE TABLE alarm_webhook_deliveries (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id          VARCHAR(36)   NOT NULL,
    event_type        VARCHAR(40)   NOT NULL,
    alarm_id          BIGINT,
    payload           TEXT          NOT NULL,
    state             VARCHAR(20)   NOT NULL,
    attempts          INTEGER       NOT NULL DEFAULT 0,
    next_attempt_at   BIGINT        NOT NULL,
    last_attempt_at   BIGINT,
    last_status_code  INTEGER,
    last_error        VARCHAR(1000),
    delivered_at      BIGINT,
    created_at        BIGINT        NOT NULL,
    CONSTRAINT uq_alarm_webhook_event UNIQUE (event_id),
    CONSTRAINT fk_alarm_webhook_alarm FOREIGN KEY (alarm_id)
        REFERENCES alarms (id) ON DELETE CASCADE,
    CONSTRAINT ck_alarm_webhook_state CHECK (state IN ('PENDING', 'DELIVERED', 'FAILED'))
);

CREATE INDEX idx_alarm_webhook_due ON alarm_webhook_deliveries (state, next_attempt_at, id);


-- -----------------------------------------------------------------------------
-- 6. Permissions
--
-- The queue and its two decisions follow the asset-status-request queue they sit beside: it is
-- the same kind of question («a reading on a finished round needs a supervisor»), asked of the
-- same people. Derived from existing grants rather than from role codes, so a duplicated role
-- inherits them like everything else (docs/security.md §3; the V16 rule).
--
-- The rules and the delivery log are administration: derived from GET:/integration-keys, the
-- authority that already means «may decide what this system tells other systems».
-- ADMIN holds both sources, so it holds every new permission
-- (BranchSchemaAndSeedRegressionTest.adminStillHoldsEveryPermissionAfterTheSeedEdits).
-- -----------------------------------------------------------------------------
