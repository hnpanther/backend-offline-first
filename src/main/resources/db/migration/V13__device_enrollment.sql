-- =============================================================================
-- V13 — Device enrolment: which handheld may use the mobile app at all
--
-- WHAT IT ADDS. Today a session belongs to a USER, and any device that knows a valid password
-- gets one. This adds the second question — WHICH DEVICE — as a separate, independent layer:
--
--   devices                  one row per physical device: its public key and its standing
--                            (PENDING / APPROVED / REVOKED). It belongs to no user — shared
--                            tablets are a supported shape (the PWA's sessionContext.ts), so a
--                            device is trusted, not "a person on a device".
--   device_auth_challenges   single-use nonces a device signs at login. Short-lived.
--   api_sessions.device_id   which device a login happened on. NULL for every session issued
--                            while enrolment is off — i.e. every row that exists today.
--
-- OFF BY DEFAULT, AND OFF MEANS INERT. `auth.device_enrollment.enabled` is seeded 'false'. With
-- it off the login path ignores every device field and behaves exactly as before this
-- migration; the enrolment endpoints refuse. Turning it on is enforced AT LOGIN ONLY: a session
-- already issued keeps working until it expires (`auth.jwt.expiry_minutes`, 8 h by default) or
-- is revoked, so switching the setting on never interrupts a round in progress.
--
-- WHY THE KEY AND NOT A RANDOM ID. The device holds a non-extractable ECDSA P-256 private key
-- created by WebCrypto; only the public half (SPKI, base64) is stored here. A random id in
-- storage is a string anybody can copy to another phone; a non-extractable key cannot be read
-- out even by the app's own JavaScript. See docs/security.md, "Device enrolment".
--
-- THE ONE-TIME CODE. An approver issues it from the panel for ONE pending request and reads it
-- to whoever is at the tablet — at the desk or over the phone. It is stored only as a SHA-256
-- hash, lives 10 minutes, allows 5 wrong attempts, and is accepted only alongside a signature
-- by the key that made THAT request — so a code overheard on the phone is useless on any other
-- device. Its columns live on the device row because a code exists only for a pending request;
-- a separate table would allow a code with no request, which is the shape this design refuses.
-- =============================================================================

CREATE TABLE devices (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_key           TEXT         NOT NULL,
    key_fingerprint      VARCHAR(64)  NOT NULL,
    label                VARCHAR(255),
    user_agent           VARCHAR(512),
    request_ip           VARCHAR(64),
    status               VARCHAR(16)  NOT NULL,
    requested_at         BIGINT       NOT NULL,
    request_expires_at   BIGINT       NOT NULL,
    code_hash            VARCHAR(64),
    code_issued_at       BIGINT,
    code_expires_at      BIGINT,
    code_issued_by       BIGINT,
    code_failed_attempts INTEGER      NOT NULL DEFAULT 0,
    approved_at          BIGINT,
    approved_by          BIGINT,
    revoked_at           BIGINT,
    revoked_by           BIGINT,
    revoke_reason        VARCHAR(16),
    last_seen_at         BIGINT,
    CONSTRAINT uk_devices_key_fingerprint UNIQUE (key_fingerprint),
    CONSTRAINT ck_devices_status CHECK (status IN ('PENDING', 'APPROVED', 'REVOKED')),
    CONSTRAINT ck_devices_revoke_reason CHECK (revoke_reason IS NULL OR revoke_reason IN ('ADMIN', 'REJECTED')),
    CONSTRAINT ck_devices_code_attempts CHECK (code_failed_attempts >= 0),
    -- The shapes a status implies, stated where no future code path can skip them.
    CONSTRAINT ck_devices_approved_shape CHECK (status <> 'APPROVED' OR approved_at IS NOT NULL),
    CONSTRAINT ck_devices_revoked_shape  CHECK (status <> 'REVOKED' OR (revoked_at IS NOT NULL AND revoke_reason IS NOT NULL)),
    -- A code is a pending request's property. An approved or revoked device never holds one.
    CONSTRAINT ck_devices_code_only_when_pending CHECK (status = 'PENDING' OR code_hash IS NULL)
);

-- Who issued, approved and revoked. RESTRICT, like every authorship column in this schema:
-- deleting a person must never delete, or orphan, the record of what they did. The user-delete
-- guard (UserRepository.isReferencedAnywhere) names all three, and
-- UserDeleteReferenceIntegrityTest fails if it ever stops doing so.
ALTER TABLE devices
    ADD CONSTRAINT fk_devices_code_issued_by FOREIGN KEY (code_issued_by) REFERENCES users (id) ON DELETE RESTRICT,
    ADD CONSTRAINT fk_devices_approved_by    FOREIGN KEY (approved_by)    REFERENCES users (id) ON DELETE RESTRICT,
    ADD CONSTRAINT fk_devices_revoked_by     FOREIGN KEY (revoked_by)     REFERENCES users (id) ON DELETE RESTRICT;

-- The panel lists by status, newest first; the pending caps count unexpired pending rows.
CREATE INDEX idx_devices_status_requested ON devices (status, requested_at DESC);
CREATE INDEX idx_devices_pending_ip ON devices (request_ip, request_expires_at) WHERE status = 'PENDING';

COMMENT ON TABLE devices IS
    'Handheld devices that may use the mobile API when auth.device_enrollment.enabled is on. '
    'Never deleted: a device that must stop is REVOKED, so who approved it stays on record.';
COMMENT ON COLUMN devices.public_key IS 'ECDSA P-256 public key, X.509 SubjectPublicKeyInfo DER, base64.';
COMMENT ON COLUMN devices.key_fingerprint IS 'SHA-256 of the SPKI DER, lowercase hex. One device per key.';
COMMENT ON COLUMN devices.code_hash IS 'SHA-256 of the one-time enrolment code. The code itself is never stored.';

-- -----------------------------------------------------------------------------
-- Login challenges
-- -----------------------------------------------------------------------------
-- A server nonce rather than a signed timestamp, and the reason is the device clock: a
-- timestamp window would refuse every login from a tablet whose clock is wrong, which the PWA
-- roadmap records as a real condition in this plant. Consumed by DELETE ... RETURNING, so a
-- nonce authenticates exactly one login. CASCADE is right here and nowhere else in this file:
-- a challenge is transient and records nobody's work.
CREATE TABLE device_auth_challenges (
    nonce      VARCHAR(64) PRIMARY KEY,
    device_id  BIGINT      NOT NULL,
    created_at BIGINT      NOT NULL,
    expires_at BIGINT      NOT NULL,
    CONSTRAINT fk_device_auth_challenges_device FOREIGN KEY (device_id) REFERENCES devices (id) ON DELETE CASCADE
);

CREATE INDEX idx_device_auth_challenges_expires ON device_auth_challenges (expires_at);
CREATE INDEX idx_device_auth_challenges_device  ON device_auth_challenges (device_id, created_at DESC);

-- -----------------------------------------------------------------------------
-- Which device a session was issued on
-- -----------------------------------------------------------------------------
-- Nullable, and NULL for every existing row: those sessions were issued while enrolment did not
-- exist, and they stay valid until they expire exactly as they would have. Revoking a device
-- revokes the sessions that name it, which is how "this tablet must stop" takes effect at the
-- next request without touching the per-request authentication path at all.
ALTER TABLE api_sessions ADD COLUMN device_id BIGINT;
ALTER TABLE api_sessions
    ADD CONSTRAINT fk_api_sessions_device FOREIGN KEY (device_id) REFERENCES devices (id) ON DELETE RESTRICT;
CREATE INDEX idx_api_sessions_device ON api_sessions (device_id) WHERE device_id IS NOT NULL;

-- -----------------------------------------------------------------------------
-- The switch. Off.
-- -----------------------------------------------------------------------------
INSERT INTO app_settings (setting_key, value, updated_at) VALUES
('auth.device_enrollment.enabled', 'false', 0)
ON CONFLICT (setting_key) DO NOTHING;

-- -----------------------------------------------------------------------------
-- Permissions for the panel page
-- -----------------------------------------------------------------------------
-- WHO GETS THEM. Whoever may already revoke a mobile session — derived from that grant, not
-- written as a list of role codes, for the reason V7 gives: a duplicated role gets a NEW code
-- and the same permissions, and a hard-coded list would leave the copy unable to do half of a
-- job it can otherwise do. Today that is ADMIN alone ('admin' category). Approval can then be
-- delegated — to a shift supervisor, say — from the Roles page, which is the point of making
-- the code issuance its own permission.
INSERT INTO permissions (code, name, category, http_method, endpoint_path) VALUES
('GET:/devices',               'لیست دستگاه‌های موبایل',          'admin', 'GET',  '/devices'),
('POST:/devices/{id}/code',    'صدور کد ثبت دستگاه',             'admin', 'POST', '/devices/{id}/code'),
('POST:/devices/{id}/revoke',  'لغو دستگاه یا رد درخواست ثبت',   'admin', 'POST', '/devices/{id}/revoke');

INSERT INTO role_permissions (role_id, permission_id)
SELECT rp.role_id, dev.id
  FROM role_permissions rp
  JOIN permissions src ON src.id = rp.permission_id
                      AND src.code = 'POST:/api-sessions/{id}/revoke'
 CROSS JOIN permissions dev
 WHERE dev.code IN ('GET:/devices', 'POST:/devices/{id}/code', 'POST:/devices/{id}/revoke')
ON CONFLICT (role_id, permission_id) DO NOTHING;
