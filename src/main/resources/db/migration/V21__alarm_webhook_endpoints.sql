-- =============================================================================
-- V21 — alarm webhooks configured in the panel, and more than one of them
--
-- Until now the webhook was ONE address in configuration (app.alarm.webhook.url / api-key):
-- changing where alarms go meant editing the server's environment and restarting it, and a plant
-- with two receivers (an SMS gateway and a CMMS, say) could feed only one.
--
-- alarm_webhook_endpoints   — every receiver an administrator has registered. Each one has its
--                             own address, its own credentials, its own choice of events and
--                             whether it receives supervisors' phone numbers.
-- alarm_webhook_endpoint_rules
--                           — which alarm rules a receiver is for, when it is not for all of them:
--                             «every alarm goes to the SMS gateway, and the boiler-pressure rule
--                             ALSO goes to the safety officer's system». A receiver is either ALL
--                             (every alarm, whatever raised it) or SELECTED (alarms raised by the
--                             rules listed here — the default rule is a row of alarm_rules like
--                             any other, so «only the default rule» is one of these lists).
-- alarm_webhook_deliveries  — gains endpoint_id: an event now becomes one delivery per active
--                             endpoint that subscribes to it, each retried and failing on its
--                             own, so one receiver being down never delays another.
--
-- WHY THIS WAS CONFIGURATION, AND WHAT REPLACES THAT GUARD. V17 kept the URL out of the database
-- on purpose: an outbound address an administrator can type is a way to point the server at an
-- internal service (SSRF). The guard is now in code and configuration rather than in «nobody can
-- type it»: AlarmWebhookTargetPolicy refuses loopback, link-local (the cloud metadata address
-- included) and unspecified addresses, at save and again before every request; an optional
-- app.alarm.webhook.allowed-hosts list bounds where an endpoint may point at all; redirects are
-- never followed; and nothing a receiver answers is ever shown — last_error keeps the status
-- code, never the body, so the delivery log cannot be used to read another service's response.
--
-- THE TWO SECRETS. api_key is what the receiver checks today (sent as X-API-Key — the V17
-- contract, unchanged). signing_secret is generated here, never typed and never sent: the request
-- carries an HMAC-SHA256 of «timestamp.body» made with it (X-Webhook-Timestamp,
-- X-Webhook-Signature), which proves the body came from this server unaltered and is fresh. Both
-- are stored as written because the server must use them on every request; neither is ever shown
-- again after it is saved, except the signing secret once, when it is created or regenerated.
--
-- THE OLD CONFIGURATION. A deployment that had app.alarm.webhook.url set gets it imported, once,
-- as an endpoint, by AlarmWebhookLegacyImportRunner on the first boot after this migration — a
-- migration cannot read the application's configuration. Pending deliveries from before this
-- version are attached to it, so nothing queued is lost.
-- =============================================================================

CREATE TABLE alarm_webhook_endpoints (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                     VARCHAR(100)  NOT NULL,
    url                      VARCHAR(2000) NOT NULL,
    api_key                  VARCHAR(500),
    signing_secret           VARCHAR(100)  NOT NULL,
    active                   BOOLEAN       NOT NULL DEFAULT TRUE,
    include_contact_details  BOOLEAN       NOT NULL DEFAULT TRUE,
    -- NULL = every alarm event; otherwise a comma-separated subset.
    event_types              VARCHAR(100),
    -- ALL = every alarm; SELECTED = only alarms of the rules in alarm_webhook_endpoint_rules.
    rule_scope               VARCHAR(20)   NOT NULL DEFAULT 'ALL',
    created_at               BIGINT        NOT NULL,
    created_by_user_id       BIGINT,
    updated_at               BIGINT        NOT NULL,
    CONSTRAINT ck_alarm_webhook_endpoints_name CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_alarm_webhook_endpoints_url CHECK (url ~* '^https?://'),
    CONSTRAINT ck_alarm_webhook_endpoints_events CHECK (
        event_types IS NULL
        OR event_types ~ '^(ALARM_RAISED|ALARM_ESCALATED)(,(ALARM_RAISED|ALARM_ESCALATED))*$'),
    CONSTRAINT ck_alarm_webhook_endpoints_rule_scope CHECK (rule_scope IN ('ALL', 'SELECTED'))
);

-- Two endpoints called the same are two rows nobody can tell apart in the delivery log.
CREATE UNIQUE INDEX ux_alarm_webhook_endpoints_name_lower ON alarm_webhook_endpoints (LOWER(name));

-- The rules a SELECTED receiver is for. Deleting the receiver takes its list with it (the list is
-- its configuration). Deleting a RULE a receiver names is refused — RESTRICT here, and asked first
-- by AlarmRuleService.delete — because a receiver whose only rule vanished would go silent with
-- nothing on any page to say so, and for the sensitive parameter it was set up for.
CREATE TABLE alarm_webhook_endpoint_rules (
    endpoint_id    BIGINT NOT NULL,
    alarm_rule_id  BIGINT NOT NULL,
    CONSTRAINT pk_alarm_webhook_endpoint_rules PRIMARY KEY (endpoint_id, alarm_rule_id),
    CONSTRAINT fk_alarm_webhook_endpoint_rules_endpoint FOREIGN KEY (endpoint_id)
        REFERENCES alarm_webhook_endpoints (id) ON DELETE CASCADE,
    CONSTRAINT fk_alarm_webhook_endpoint_rules_rule FOREIGN KEY (alarm_rule_id)
        REFERENCES alarm_rules (id)
);

-- The rule delete guard asks «does any receiver name this rule».
CREATE INDEX idx_alarm_webhook_endpoint_rules_rule ON alarm_webhook_endpoint_rules (alarm_rule_id);

-- ON DELETE SET NULL, and the name frozen beside it: deleting a receiver must not erase the record
-- of what was sent to it. Its pending deliveries are failed by the delete itself
-- (AlarmWebhookEndpointService.delete), so nothing is left waiting for an address that is gone.
ALTER TABLE alarm_webhook_deliveries
    ADD COLUMN endpoint_id BIGINT
        CONSTRAINT fk_alarm_webhook_deliveries_endpoint REFERENCES alarm_webhook_endpoints (id) ON DELETE SET NULL;

ALTER TABLE alarm_webhook_deliveries
    ADD COLUMN endpoint_name VARCHAR(100);

-- One event, many receivers: the event id is shared by its deliveries — it is the same event, and
-- each receiver deduplicates on it — so it is unique per endpoint rather than across the table.
ALTER TABLE alarm_webhook_deliveries DROP CONSTRAINT uq_alarm_webhook_event;
CREATE UNIQUE INDEX ux_alarm_webhook_deliveries_event_endpoint
    ON alarm_webhook_deliveries (event_id, endpoint_id);

-- event_type has no CHECK (V17), so a test request from the panel — WEBHOOK_TEST — is a delivery
-- like any other: retried, logged and seen. alarm_id is NULL on it.

CREATE INDEX idx_alarm_webhook_deliveries_endpoint ON alarm_webhook_deliveries (endpoint_id)
    WHERE endpoint_id IS NOT NULL;

